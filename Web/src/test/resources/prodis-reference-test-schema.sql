-- Testbron voor de alleen-lezen Prodis-database (legacy-config S5; docs/design/legacy-config-bundle-design.md par. 6;
-- publicatie P1: docs/design/publicatie-prodis-db-direct-design.md par. 2.3/5).
-- Exact de tabellen en kolommen die CatalogImport mag lezen (de GRANT van catalogimport_ro), met de namen en types uit
-- de Prodis-Liquibase (20260114074920 supplier, 20260114074921 + 20260519120000 supplier_group, 20260418235900 +
-- 20260427120000 supplier_catalog, catalog_article* en language uit de Prodis-DB, system_settings 20261008100000).
-- supplier.number is in Prodis NIET uniek; supplier_catalog kan per scope_key meerdere rijen hebben (historiek per status).
-- Idempotent (ProdisReferenceTestDatabase.named voert het eenmaal per database uit).
create table if not exists supplier (
    id     bigint generated by default as identity primary key,
    number varchar(255),
    name   varchar(255) not null
);
create table if not exists supplier_group (
    id            bigint generated by default as identity primary key,
    supplier_id   bigint,
    group_name    varchar(255),
    discount_code varchar(255),
    legacy_code   varchar(80)
);
create table if not exists supplier_catalog (
    id            bigint generated by default as identity primary key,
    supplier_id   bigint not null,
    scope_key     varchar(255) not null,
    legacy_number varchar(255),
    catalog_name  varchar(255) not null,
    status        varchar(255) not null
);
create table if not exists language (
    id   bigint generated by default as identity primary key,
    code varchar(255) not null
);
create table if not exists system_settings (
    id            bigint generated by default as identity primary key,
    legacy_master varchar(16) not null
);
create table if not exists catalog_article (
    id                          bigint generated by default as identity primary key,
    supplier_id                 bigint not null,
    supplier_group_id           bigint not null,
    supplier_catalog_id         bigint not null,
    supplier_reference_stripped varchar(255) not null,
    record_active               boolean not null default true,
    deleted_at                  timestamp
);
create table if not exists catalog_article_price (
    id                       bigint generated by default as identity primary key,
    catalog_article_id       bigint not null,
    price_code               varchar(255),
    brut_price_politics      varchar(255),
    base_price               numeric(21, 6),
    brut_price               double precision,
    brut_price_percentage    double precision,
    sales_price_last_updated timestamp,
    record_active            boolean not null default true,
    deleted_at               timestamp
);
create table if not exists catalog_article_price_detail (
    id                       bigint generated by default as identity primary key,
    catalog_article_price_id bigint,
    code                     varchar(255) not null,
    percentage               double precision,
    price                    double precision,
    record_active            boolean not null default true,
    deleted_at               timestamp
);
create table if not exists catalog_article_description (
    id                 bigint generated by default as identity primary key,
    catalog_article_id bigint not null,
    language_id        bigint not null,
    description        varchar(255) not null,
    record_active      boolean not null default true,
    deleted_at         timestamp
);
