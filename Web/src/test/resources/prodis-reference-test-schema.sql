-- Testbron voor de alleen-lezen Prodis-database (legacy-config S5; docs/design/legacy-config-bundle-design.md par. 6).
-- Exact de tabellen en kolommen die CatalogImport mag lezen (de GRANT van catalogimport_ro), met de namen en types uit
-- de Prodis-Liquibase (20260114074920 supplier, 20260114074921 + 20260519120000 supplier_group, 20260418235900 +
-- 20260427120000 supplier_catalog). supplier.number is in Prodis NIET uniek; supplier_catalog kan per scope_key meerdere
-- rijen hebben (historiek per status). Idempotent (ProdisReferenceTestDatabase.named voert het eenmaal per database uit).
create table if not exists supplier (
    id     bigint generated by default as identity primary key,
    number varchar(255),
    name   varchar(255) not null
);
create table if not exists supplier_group (
    id            bigint generated by default as identity primary key,
    supplier_id   bigint,
    group_name    varchar(255),
    discount_code varchar(255),
    legacy_code   varchar(80)
);
create table if not exists supplier_catalog (
    id            bigint generated by default as identity primary key,
    supplier_id   bigint not null,
    scope_key     varchar(255) not null,
    legacy_number varchar(255),
    catalog_name  varchar(255) not null,
    status        varchar(255) not null
);
