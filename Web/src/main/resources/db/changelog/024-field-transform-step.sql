-- Legacy-config S8c: de transformatieketen van een veldmapping (docs/design/legacy-config-s8-design.md par. 2c en 3;
-- docs/design/legacy-config-bundle-design.md par. 4 "024-field-transform-step"). Volledig ADDITIEF: geen bestaande
-- tabel, kolom of constraint wijzigt; er wordt niets gebackfilld.
--
-- Waarom een eigen tabel: legacy past per PSIMPDEF-regel een vaste pijplijn toe (Prg_1170 r.730-732, r.1039-1115):
-- MID op de ruwe waarde -> Trim -> enkel indien niet leeg Trim(prefix) & v & Trim(suffix) -> hoogstens een CALC. Een
-- mapping draagt maar een transform_kind; een mapping met transform_kind CHAIN krijgt haar stappen hier. Een stap is
-- een soort uit de gesloten lijst plus haar instellingen, geen vrije expressie (beslissingslog Q9).
--
-- Regels:
--   * step_number 1..3 en uniek per mapping: hoogstens substring, prefix/suffix en een waardebewerking.
--   * transform_kind is nooit CHAIN (een keten in een keten bestaat niet). De volledige grammatica
--     ([SUBSTRING] -> [AFFIX|PREFIX|SUFFIX] -> [UPPER|MAP|...]) bewaakt de configuratievalidatie
--     (CONFIG_TRANSFORM_INVALID), net als voor transform_kind van de mapping (geen check, 004-2).
--   * transform_config varchar(1000) zoals import_field_mapping.transform_config.
--   * created_at/created_by/created_by_subject zoals de mapping zelf (004-2, 007-4).
--   * Geen "on delete cascade" (zoals elke FK in dit schema): de applicatie verwijdert de stappen voor hun mapping.
--   * De vertaalrijen van een MAP-stap blijven in import_field_value_map, aan de mapping (023-1).
--
-- De stappen horen bij een bevroren revisie zoals de mapping zelf: ze worden enkel in een DRAFT geschreven of verwijderd.
--
-- Rollback: de tabel verdwijnt met haar rijen; een CHAIN-mapping zonder stappen wordt dan CONFIG_TRANSFORM_INVALID.

--changeset catalogimport:024-1-import-field-transform-step
--comment S8c: transformatieketen per veldmapping (1-3 stappen), legacy PSIMPDEF-pijplijn; additief.
create table import_field_transform_step (
    id                 bigint generated by default as identity,
    mapping_id         bigint not null,
    step_number        integer not null,
    transform_kind     varchar(30) not null,
    transform_config   varchar(1000),
    created_at         timestamp with time zone not null,
    created_by         varchar(100),
    created_by_subject varchar(255),
    constraint pk_import_field_transform_step primary key (id),
    constraint uk_import_field_transform_step_number unique (mapping_id, step_number),
    constraint fk_import_field_transform_step_mapping foreign key (mapping_id)
        references import_field_mapping (id),
    constraint ck_import_field_transform_step_number
        check (step_number between 1 and 3),
    constraint ck_import_field_transform_step_kind
        check (transform_kind <> 'CHAIN'),
    constraint ck_import_field_transform_step_created_subject
        check (created_by_subject is null or created_by is not null)
);

