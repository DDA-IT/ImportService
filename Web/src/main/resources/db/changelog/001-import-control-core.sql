create table source_organisation (
    id                bigint generated by default as identity,
    code              varchar(50) not null,
    name              varchar(200) not null,
    organisation_type varchar(40) not null,
    active            boolean not null default true,
    created_at        timestamp with time zone not null,
    updated_at        timestamp with time zone not null,
    constraint pk_source_organisation primary key (id),
    constraint uk_source_organisation_code unique (code)
);

create table import_definition (
    id                          bigint generated by default as identity,
    source_organisation_id      bigint not null,
    code                        varchar(50) not null,
    description                 varchar(200) not null,
    usage_type                  varchar(40) not null,
    superseded_by_definition_id bigint,
    based_on_definition_id      bigint,
    created_at                  timestamp with time zone not null,
    created_by                  varchar(100) not null,
    updated_at                  timestamp with time zone not null,
    constraint pk_import_definition primary key (id),
    constraint uk_import_definition_code unique (source_organisation_id, code),
    constraint fk_import_definition_source_organisation foreign key (source_organisation_id) references source_organisation (id),
    constraint fk_import_definition_superseded_by foreign key (superseded_by_definition_id) references import_definition (id),
    constraint fk_import_definition_based_on foreign key (based_on_definition_id) references import_definition (id)
);

-- active_marker is TRUE zolang de revisie ACTIVE is en NULL in elke andere toestand.
-- NULL-waarden botsen niet in een UNIQUE constraint, dus dit dwingt "hoogstens een actieve
-- revisie per definitie" op databaseniveau af (businessanalyse 14.14).
create table import_definition_revision (
    id                               bigint generated by default as identity,
    import_definition_id             bigint not null,
    revision_number                  integer not null,
    status                           varchar(40) not null,
    active_marker                    boolean,
    access_version                   integer not null,
    access_config_hash               varchar(64) not null,
    structure_version                integer not null,
    structure_config_hash            varchar(64) not null,
    record_rules_version             integer not null,
    record_rules_config_hash         varchar(64) not null,
    composite_config_hash            varchar(64) not null,
    identity_profile_kind            varchar(40) not null,
    identity_supplier_field          varchar(200) not null,
    identity_supplier_group_field    varchar(200) not null,
    identity_supplier_reference_field varchar(200) not null,
    identity_discount_code_field     varchar(200),
    based_on_revision_id             bigint,
    change_reason                    varchar(500),
    created_at                       timestamp with time zone not null,
    created_by                       varchar(100) not null,
    updated_at                       timestamp with time zone not null,
    approved_at                      timestamp with time zone,
    approved_by                      varchar(100),
    constraint pk_import_definition_revision primary key (id),
    constraint uk_import_definition_revision_number unique (import_definition_id, revision_number),
    constraint uk_import_definition_revision_active unique (import_definition_id, active_marker),
    constraint fk_import_definition_revision_definition foreign key (import_definition_id) references import_definition (id),
    constraint fk_import_definition_revision_based_on foreign key (based_on_revision_id) references import_definition_revision (id),
    constraint ck_import_definition_revision_identity check (
        (identity_profile_kind = 'THREE_PART' and identity_discount_code_field is null)
        or (identity_profile_kind = 'FOUR_PART_WITH_DISCOUNT_CODE' and identity_discount_code_field is not null)
    )
);

