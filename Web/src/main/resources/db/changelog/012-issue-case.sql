--changeset catalogimport:012-2-issue-case-event
--comment Append-only auditregister van het behandelgeval (design par. 1/§2, R-CASE-04). Nooit bijgewerkt, nooit verwijderd - patroon publication_decision (005-3).

-- Zonder deze tabel zou een systeemheropening de afwijzingsreden van de mens overschrijven: dat botst
-- met BA §13 r.1006 ("Iedere actie bewaart gebruiker, tijd, reden") en met AGENT.md Fase 4.
--
-- previous_status is null enkel bij CREATED (er is nog geen vorige status). source bepaalt of
-- changed_by/changed_by_subject gevuld mogen zijn: HUMAN draagt altijd een naam, SYSTEM nooit.
create table issue_case_event (
    id                        bigint generated by default as identity,
    issue_case_id             bigint not null,
    event_kind                varchar(30) not null,
    previous_status           varchar(30),
    new_status                varchar(30) not null,
    reason                    varchar(500) not null,
    source                    varchar(20) not null,
    changed_by                varchar(100),
    changed_by_subject        varchar(255),
    changed_at                timestamp with time zone not null,
    observation_batch_id      bigint,
    constraint pk_issue_case_event primary key (id),
    constraint fk_issue_case_event_case foreign key (issue_case_id) references issue_case (id),
    constraint fk_issue_case_event_batch foreign key (observation_batch_id) references import_batch (id),
    constraint ck_issue_case_event_kind check (event_kind in ('CREATED', 'STATUS_CHANGE')),
    constraint ck_issue_case_event_status check (
        (previous_status is null or previous_status in ('AWAITING_REVIEW', 'CORRECTED', 'REJECTED', 'AUTO_RESOLVED'))
        and new_status in ('AWAITING_REVIEW', 'CORRECTED', 'REJECTED', 'AUTO_RESOLVED')
    ),
    constraint ck_issue_case_event_previous
        check (event_kind <> 'CREATED' or previous_status is null),
    constraint ck_issue_case_event_source
        check ((source = 'HUMAN' and changed_by is not null)
            or (source = 'SYSTEM' and changed_by is null and changed_by_subject is null)),
    constraint ck_issue_case_event_subject
        check (changed_by_subject is null or changed_by is not null)
);

-- Sortering op id, geen sequence_no (patroon publication_decision): het chronologisch verloop van
-- één geval, in insertievolgorde.
create index idx_issue_case_event_case on issue_case_event (issue_case_id, id);

