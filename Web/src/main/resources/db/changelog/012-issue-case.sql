--changeset catalogimport:012-1-issue-case
--comment Het behandelgeval: één rij per (import_link_id, issue_code, signature) - de observatie-eenheid van een terugkerend probleem (design par. 1, R-CASE-01).

-- Identiteit (D1): (import_link_id, issue_code, signature) is uniek, dus herhaling van hetzelfde
-- probleem creëert nooit een tweede geval (R-CASE-01).
--
-- severity/issue_domain/control_level/impact_scope/incident_kind zijn gedenormaliseerd bij aanmaak
-- uit de eerste groep en worden daarna nooit bijgewerkt: de classificatie mag niet van de wijzigbare
-- foutcodecatalogus afhangen (zelfde motivatie als import_issue_group, R-ISS-02).
--
-- observation_count/total_occurrence_count/first_seen_at/last_seen_at worden altijd herberekend,
-- nooit "+1" - net als een teller op import_batch, nooit stil 0 wanneer niet gemeten.
--
-- status_changed_at/status_changed_by/status_changed_by_subject volgen het *_by/*_by_subject-paar
-- van changeset 007 (OIDC-subject nullable = geen geverifieerde identiteit, of systeemheropening).
create table issue_case (
    id                          bigint generated by default as identity,
    import_link_id              bigint not null,
    issue_code                  varchar(60) not null,
    signature                   varchar(300) not null,
    severity                    varchar(20) not null,
    issue_domain                varchar(40) not null,
    control_level               varchar(20) not null,
    impact_scope                varchar(20) not null,
    incident_kind               varchar(30) not null,
    price_component_code        varchar(20),
    reference_type              varchar(30),
    status                      varchar(30) not null,
    observation_count           bigint not null,
    total_occurrence_count      bigint not null,
    first_seen_at               timestamp with time zone not null,
    last_seen_at                timestamp with time zone not null,
    first_seen_batch_id         bigint not null,
    last_seen_batch_id          bigint not null,
    last_seen_revision_id       bigint not null,
    reopen_count                integer not null default 0,
    status_reason               varchar(500),
    status_changed_at           timestamp with time zone,
    status_changed_by           varchar(100),
    status_changed_by_subject   varchar(255),
    decision_revision_id        bigint,
    created_at                  timestamp with time zone not null,
    updated_at                  timestamp with time zone not null,
    constraint pk_issue_case primary key (id),
    constraint uk_issue_case_identity unique (import_link_id, issue_code, signature),
    constraint fk_issue_case_import_link foreign key (import_link_id) references import_link (id),
    constraint fk_issue_case_first_batch foreign key (first_seen_batch_id) references import_batch (id),
    constraint fk_issue_case_last_batch foreign key (last_seen_batch_id) references import_batch (id),
    constraint fk_issue_case_last_revision foreign key (last_seen_revision_id)
        references import_definition_revision (id),
    constraint fk_issue_case_decision_revision foreign key (decision_revision_id)
        references import_definition_revision (id),
    -- Geen ACCEPTED_*, geen DETECTED (D3): het behandelgeval laat per definitie niets door.
    constraint ck_issue_case_status
        check (status in ('AWAITING_REVIEW', 'CORRECTED', 'REJECTED', 'AUTO_RESOLVED')),
    constraint ck_issue_case_status_change
        check (status_changed_at is null or status_reason is not null),
    constraint ck_issue_case_decided
        check (status = 'AWAITING_REVIEW' or (status_changed_at is not null and status_reason is not null)),
    constraint ck_issue_case_status_subject
        check (status_changed_by_subject is null or status_changed_by is not null),
    -- Een geval zonder waarnemingen mag alleen bestaan als er al een menselijke actie op staat
    -- (herstelpad ScreeningRecoveryService, S2-B1b).
    constraint ck_issue_case_observations
        check (observation_count >= 0 and (observation_count > 0 or status_changed_at is not null))
);

create index idx_issue_case_link_status on issue_case (import_link_id, status);
create index idx_issue_case_status_last_seen on issue_case (status, last_seen_at);

