--changeset catalogimport:013-3-secret-key-check
--comment Controlewaarde per sleutel: hoort deze sleutel bij deze database (credentials-design par. 5.3, A7, V7).

-- check_value is een vaste, bekende tekst versleuteld met de sleutel key_id onder de eigen associated
-- data catalogimport|secret_key_check|<keyId>|v1 (niet die van een credential). Bij het opstarten
-- ontsleutelt SecretKeyCheckVerifier elke geconfigureerde sleutel hiertegen: lukt dat niet, dan start
-- de applicatie niet (een sleutel met dezelfde ID maar ander materiaal hoort niet bij deze database).
-- Een rij wordt nooit bijgewerkt: ander materiaal onder dezelfde ID is precies wat gedetecteerd moet worden.
create table secret_key_check (
    key_id        varchar(32) not null,
    check_value   text not null,
    created_at    timestamp with time zone not null,
    constraint pk_secret_key_check primary key (key_id)
);

--rollback drop table secret_key_check;

--changeset catalogimport:013-4-bound-host-normalized
--comment DB-afgedwongen genormaliseerde bound_host (credentials-design par. 5.1, beslissingslog 2026-09-29 K-2a (b)); additief, 013-1 blijft ongewijzigd.

-- De host-binding (uk_external_credential_host_binding, L4a) vergelijkt strings exact. Een host die enkel in
-- hoofdletters, met een punt achteraan of met spaties verschilt, zou een credential aan "dezelfde" host
-- kunnen binden onder een andere spelling. Daarom weigert de database alles wat niet genormaliseerd is:
-- niet leeg (na trim), gelijk aan lower(), geen punt achteraan en geen enkele witruimte. Normaliseren zelf
-- hoort in de CredentialService (K-3); hier wordt enkel geweigerd.
alter table external_credential
    add constraint ck_external_credential_bound_host_normalized
    check (length(btrim(bound_host)) > 0
        and bound_host = lower(bound_host)
        and right(bound_host, 1) <> '.'
        and bound_host !~ '[[:space:]]');

--rollback alter table external_credential drop constraint ck_external_credential_bound_host_normalized;
