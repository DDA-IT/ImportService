--changeset catalogimport:006-4-import-link-bookmark-value
--comment LINK-scope waarde: de per importkoppeling ingevulde bookmarkwaarde (decisions.md 2026-09-23, keuze 1 en 2).

-- GEEN foreign key naar import_definition_bookmark, en dat is een uitdrukkelijke ontwerpkeuze
-- (decisions.md 2026-09-23): de declaratie hangt aan een REVISIE en verdwijnt dus bij elke
-- opvolgrevisie van het sjabloon, terwijl de koppeling blijft bestaan. Met een FK zou elke nieuwe
-- sjabloonversie de ingevulde leverancierswaarden ongeldig maken of meeslepen. De koppeling gebeurt
-- daarom op bookmark_name; data_type staat gedenormaliseerd mee zodat de waarde ook leesbaar blijft
-- wanneer de declaratie van toen niet meer bestaat (zelfde redenering als R-ISS-02 voor issuerijen).
--
-- Keerzijde die de servicelaag moet opvangen: een naam die in de nieuwe sjabloonversie niet meer
-- gedeclareerd is, blijft hier als wees staan. Dat is bewust - de waarde is auditmateriaal - maar de
-- materialisatie moet zo'n wees tonen en niet stilzwijgend toepassen.
--
-- previous_value_text/updated_at/updated_by vormen samen de wijzigingsaudit: een bookmarkwaarde
-- bepaalt mee wat er geïmporteerd en gepubliceerd wordt, dus een wijziging mag nooit alleen in een
-- logregel bestaan. De twee checks beletten een halve audit (wel tijdstip, geen naam) en een vorige
-- waarde zonder wijziging die haar verklaart.
create table import_link_bookmark_value (
    id                  bigint generated by default as identity,
    import_link_id      bigint not null,
    bookmark_name       varchar(60) not null,
    data_type           varchar(40) not null,
    value_text          varchar(500) not null,
    previous_value_text varchar(500),
    filled_at           timestamp with time zone not null,
    filled_by           varchar(100) not null,
    updated_at          timestamp with time zone,
    updated_by          varchar(100),
    constraint pk_import_link_bookmark_value primary key (id),
    constraint uk_import_link_bookmark_value unique (import_link_id, bookmark_name),
    constraint fk_import_link_bookmark_value_link foreign key (import_link_id)
        references import_link (id),
    constraint ck_import_link_bookmark_value_data_type
        check (data_type in ('TEXT', 'INTEGER', 'DECIMAL', 'DATE', 'BOOLEAN', 'ENUM',
                             'SUPPLIER_REFERENCE', 'LIBRARY_REFERENCE', 'POLICY_PROFILE_REFERENCE')),
    constraint ck_import_link_bookmark_value_updated
        check ((updated_at is null and updated_by is null)
            or (updated_at is not null and updated_by is not null)),
    constraint ck_import_link_bookmark_value_previous
        check (previous_value_text is null or updated_at is not null)
);

--rollback drop table import_link_bookmark_value;

--changeset catalogimport:006-5-import-link-definition-usage-guard
--comment Databaseguard: een sjabloon (REUSABLE_TEMPLATE) kan nooit aan een importkoppeling hangen (decisions.md 2026-09-23, keuze 7).

-- Een sjabloon is een blauwdruk, geen live configuratie (par. 14.16). Zou een ImportLink toch aan een
-- sjabloon kunnen hangen, dan zou dat sjabloon leveringen, batches, mutaties en uiteindelijk een
-- publicatie krijgen. Keuze 7 legt die grens daarom in de DATABASE en niet enkel in de servicelaag:
-- ook een toekomstige servicebug mag dit niet kunnen.
--
-- Constructie in drie stappen, zonder ook maar één bestaande kolom aan te raken:
--   1. import_definition krijgt een extra UNIQUE (id, usage_type). Functioneel overbodig (id is al
--      pk), maar een samengestelde foreign key vereist een unieke sleutel op exact die twee kolommen.
--   2. import_link krijgt een NIEUWE kolom definition_usage_type met default 'OWN_DEFINITION', zodat
--      alle bestaande rijen geldig blijven zonder datamigratie.
--   3. de samengestelde FK (import_definition_id, definition_usage_type) -> (id, usage_type) plus de
--      check definition_usage_type = 'OWN_DEFINITION' maken samen de uitspraak hard: de gekoppelde
--      definitie MOET usage_type 'OWN_DEFINITION' hebben. De check alleen zou niets zeggen over de
--      definitie; de FK alleen zou ook REUSABLE_TEMPLATE toelaten.
--
-- Nevengevolg dat we bewust willen: zolang er een ImportLink naar een definitie wijst, kan die
-- definitie niet meer op REUSABLE_TEMPLATE gezet worden - de FK weigert dat. Een live definitie
-- achteraf tot sjabloon ombouwen terwijl ze leveringen ontvangt, was toch al nooit de bedoeling.
--
-- De kolom is BEWUST NIET gemapt op de ImportLink-entiteit: ze draagt altijd dezelfde waarde en heeft
-- geen businessbetekenis in Java. Hibernate laat een niet-gemapte kolom bij het invoegen weg, waarna
-- de default hem vult, en ddl-auto: validate klaagt niet over een extra kolom in de tabel.
--
-- Migratierisico, uitdrukkelijk: bestaat er in een omgeving al een import_link naar een
-- REUSABLE_TEMPLATE-definitie, dan FAALT deze changeset op de FK. Dat is de bedoeling - zo'n rij is
-- precies de toestand die de guard verbiedt en moet met de hand rechtgezet worden, niet stil
-- omgezet.
alter table import_definition add constraint uk_import_definition_id_usage unique (id, usage_type);

alter table import_link add column definition_usage_type varchar(40) not null default 'OWN_DEFINITION';

alter table import_link add constraint ck_import_link_definition_usage_type
    check (definition_usage_type = 'OWN_DEFINITION');

alter table import_link add constraint fk_import_link_definition_usage
    foreign key (import_definition_id, definition_usage_type)
    references import_definition (id, usage_type);

