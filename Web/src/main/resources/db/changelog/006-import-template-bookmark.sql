-- bestaat pas vanaf PostgreSQL 15. translate() is GEEN alternatief: in H2 verwijdert die de extra
-- tekens niet (feitelijk nagegaan), zodat een portable variant stilzwijgend niets zou controleren -
-- erger dan geen check. Beide varianten leggen dezelfde constraintnaam en dezelfde regel op:
-- BESTANDS_PREFIX mag, bad-name of 1CULTUUR niet.

