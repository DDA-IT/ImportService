--changeset catalogimport:006-1-import-definition-bookmark
--comment Declaratie van een bookmark op REVISIENIVEAU van een sjabloon (decisions.md 2026-09-23, keuze 1).

-- De declaratie hangt aan de REVISIE, niet aan de definitie: een sjabloon dat een bookmark
-- toevoegt of laat vallen is een nieuwe sjabloonversie, precies zoals elke andere structuurwijziging
-- (par. 14.14). Gevolg dat verderop terugkomt: declaratierijen verdwijnen bij elke opvolgrevisie,
-- terwijl ingevulde waarden per koppeling moeten blijven leven - daarom koppelt
-- import_link_bookmark_value op bookmark_name en niet met een FK naar deze tabel.
--
-- value_scope is VERPLICHT en heeft bewust geen default (keuze 1): DEFINITION wordt bij
-- materialisatie in de afgeleide revisie vastgezet, LINK wordt per importkoppeling ingevuld. Een
-- stille default zou een per-leverancier-verschillende waarde in een gedeelde definitie kunnen
-- vastzetten, wat keuze 2 juist verbiedt.
--
-- required staat op TRUE als default: een bookmark bestaat om ingevuld te worden, en een niet
-- ingevuld verplicht veld moet blokkeren (keuze 6) in plaats van stil leeg te blijven. Een optionele
-- bookmark moet dus uitdrukkelijk als optioneel gedeclareerd worden.
--
-- allowed_values/validation_pattern zijn declaratiemetadata voor de invoervalidatie in de
-- servicelaag; de database dwingt hier enkel af dat een ENUM-bookmark zonder waardenlijst niet kan
-- bestaan (een keuzelijst zonder keuzes is altijd een configuratiefout).
--
-- owner_role blijft een vrije rolcode zonder waardecheck: CatalogImport heeft geen eigen
-- rollentabel - rechten komen uit Prodis (docs/decisions.md 2026-09-18 "opslag van
-- CatalogImport-permissies"). Een enumcheck hier zou een rollenmodel vastleggen dat nog niet bestaat.
create table import_definition_bookmark (
    id                     bigint generated by default as identity,
    definition_revision_id bigint not null,
    name                   varchar(60) not null,
    label                  varchar(200) not null,
    description            varchar(500),
    data_type              varchar(40) not null,
    value_scope            varchar(20) not null,
    owner_role             varchar(40) not null,
    required               boolean not null default true,
    default_value          varchar(500),
    allowed_values         varchar(2000),
    validation_pattern     varchar(200),
    sort_order             integer not null,
    created_at             timestamp with time zone not null,
    created_by             varchar(100),
    constraint pk_import_definition_bookmark primary key (id),
    constraint uk_import_definition_bookmark_name unique (definition_revision_id, name),
    constraint uk_import_definition_bookmark_order unique (definition_revision_id, sort_order),
    constraint fk_import_definition_bookmark_revision foreign key (definition_revision_id)
        references import_definition_revision (id),
    constraint ck_import_definition_bookmark_data_type
        check (data_type in ('TEXT', 'INTEGER', 'DECIMAL', 'DATE', 'BOOLEAN', 'ENUM',
                             'SUPPLIER_REFERENCE', 'LIBRARY_REFERENCE', 'POLICY_PROFILE_REFERENCE')),
    constraint ck_import_definition_bookmark_scope
        check (value_scope in ('DEFINITION', 'LINK')),
    constraint ck_import_definition_bookmark_enum
        check (data_type <> 'ENUM' or allowed_values is not null)
);

