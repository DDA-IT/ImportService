--changeset catalogimport:006-2-import-definition-bookmark-usage
--comment Witte lijst van configuratieplaatsen waar een bookmark toegepast mag worden (decisions.md 2026-09-23, keuze 3).

-- Dit is een WITTE lijst, geen vrije verwijzing: een bookmark mag alleen toegepast worden op een
-- plaats die hier uitdrukkelijk toegelaten is. Een bookmark die nergens toegepast wordt, is een
-- invulveld dat niets doet; een bookmark die overal mag, is niet meer te overzien bij het
-- materialiseren.
--
-- DELIVERY_FILE_SELECTION (het BA1-voorbeeld BESTANDS_PREFIX) staat hier BEWUST NIET in
-- (decisions.md 2026-09-23 keuze 3, fase3-rules-design.md par. 2 "Important technical constraint
-- discovered"): bestandsselectie hoort bij een Leveringsconfiguratie-entiteit die nog niet bestaat.
-- Een bookmarkplaats toelaten die nergens toegepast kan worden, levert een invulveld op dat de
-- gebruiker moet invullen zonder dat het ooit effect heeft. De waarde komt er additief bij zodra
-- Leveringsconfiguratie gebouwd is.
--
-- target_hint is NOT NULL met default '' en niet nullable: in een UNIQUE constraint botsen
-- NULL-waarden niet met elkaar, zodat twee rijen (bookmark, FIELD_MAPPING_FIXED_VALUE, NULL) naast
-- elkaar zouden kunnen bestaan en de witte lijst stilzwijgend dubbel zou raken. '' betekent hier
-- "geen nadere aanduiding", en dat is precies één waarde.
create table import_definition_bookmark_usage (
    id          bigint generated by default as identity,
    bookmark_id bigint not null,
    place_kind  varchar(40) not null,
    target_hint varchar(200) not null default '',
    created_at  timestamp with time zone not null,
    constraint pk_import_definition_bookmark_usage primary key (id),
    constraint uk_import_definition_bookmark_usage unique (bookmark_id, place_kind, target_hint),
    constraint fk_import_definition_bookmark_usage_bookmark foreign key (bookmark_id)
        references import_definition_bookmark (id),
    constraint ck_import_definition_bookmark_usage_place
        check (place_kind in ('FIELD_MAPPING_FIXED_VALUE', 'RECORD_FILTER_COMPARE_VALUE',
                              'REVISION_IDENTITY_FIELD', 'REVISION_PRICE_POLICY',
                              'LINK_LIBRARY_CODE', 'LINK_SEARCH_SUPPLIER',
                              'LINK_SUPPLIER_ORGANISATION'))
);

--rollback drop table import_definition_bookmark_usage;

--changeset catalogimport:006-3-import-definition-bookmark-value
--comment DEFINITION-scope snapshot: de bookmarkwaarde zoals ze bij materialisatie in de afgeleide revisie vastgezet is (decisions.md 2026-09-23, keuze 1).

-- Materialisatie schrijft de waarde LETTERLIJK in de doelkolom van de afgeleide revisie
-- (import_field_mapping.fixed_value met value_kind 'FIXED_VALUE', import_record_filter.compare_value,
-- een identity_*_field). Zie fase3-rules-design.md par. 2, aanvullingen bij 004-2 en 004-3: voor
-- recordfilters is dat niet één van twee opties maar de enige die werkt zonder een bestaande tabel te
-- wijzigen. Deze tabel is daarom de ENIGE plek waar de herkomst van zo'n gematerialiseerde waarde nog
-- af te lezen is; zonder deze rij is achteraf niet meer vast te stellen dat een vaste waarde uit een
-- sjabloon kwam en uit welke sjabloonversie.
--
-- value_text is NOT NULL en mag '' zijn. Dat onderscheid is hier hard: '' betekent "uitdrukkelijk
-- leeg ingevuld", terwijl "niet ingevuld" wordt uitgedrukt door de AFWEZIGHEID van een rij. Een
-- nullable kolom zou die twee toestanden op één waarde laten vallen, precies de fout die de
-- aanbiedingsidentiteit elders al vermijdt (decisions.md 2026-09-18: null is niet "").
--
-- value_text is varchar(500), gelijk aan import_field_mapping.fixed_value en
-- import_record_filter.compare_value: een langere waarde zou wel opgeslagen kunnen worden maar bij
-- materialisatie niet meer in de doelkolom passen, en dan pas afbreken.
--
-- source_template_revision_id is nullable: de sjabloonrevisie is bekend bij een materialisatie uit
-- een sjabloon, maar een handmatig ingevulde waarde op een gewone definitie heeft geen bron.
create table import_definition_bookmark_value (
    id                          bigint generated by default as identity,
    definition_revision_id      bigint not null,
    bookmark_name               varchar(60) not null,
    data_type                   varchar(40) not null,
    value_text                  varchar(500) not null,
    source_template_revision_id bigint,
    filled_at                   timestamp with time zone not null,
    filled_by                   varchar(100) not null,
    constraint pk_import_definition_bookmark_value primary key (id),
    constraint uk_import_definition_bookmark_value unique (definition_revision_id, bookmark_name),
    constraint fk_import_definition_bookmark_value_revision foreign key (definition_revision_id)
        references import_definition_revision (id),
    constraint fk_import_definition_bookmark_value_template foreign key (source_template_revision_id)
        references import_definition_revision (id),
    constraint ck_import_definition_bookmark_value_data_type
        check (data_type in ('TEXT', 'INTEGER', 'DECIMAL', 'DATE', 'BOOLEAN', 'ENUM',
                             'SUPPLIER_REFERENCE', 'LIBRARY_REFERENCE', 'POLICY_PROFILE_REFERENCE'))
);

