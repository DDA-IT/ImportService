--changeset catalogimport:014-2-connection-profile-version
--comment Onveranderlijke versie van een verbindingsprofiel; de samengestelde FK naar external_credential maakt een credential van een andere host onmogelijk (L4a, Ontdekking 2).

-- De samengestelde FK (credential_id, credential_secret_kind, credential_host) verwijst naar
-- uk_external_credential_host_binding (id, secret_kind, bound_host) uit 013-1. Samen met
-- ck_connection_profile_version_credential_host (credential_host = host) kan een profielversie met een eigen
-- host en de credential van een andere host niet bestaan: het wachtwoord kan dus nooit naar een andere server
-- gestuurd worden dan waaraan het gebonden is. De auth_method-checks houden de soort credential in lijn met de
-- gekozen authenticatie (v1 gebruikt enkel PASSWORD, A5; PRIVATE_KEY blijft gereserveerd).
--
-- host_key_algorithm/host_key_fingerprint_sha256 zijn de verplichte vastgepinde hostsleutel (L5). host volgt
-- dezelfde normalisatiecheck als external_credential.bound_host (013-4): niet leeg, kleine letters, geen punt
-- achteraan, geen witruimte. Normaliseren zelf hoort in de service (LC-2).
--
-- config_hash (varchar(64), hex) is verplicht: de service berekent hem bij elke nieuwe versie zodat een
-- identieke inhoud herkend wordt. based_on_version_id verwijst naar de versie waarop deze is gebaseerd (null bij
-- de eerste versie).
create table connection_profile_version (
    id                              bigint generated by default as identity,
    connection_profile_id           bigint not null,
    version_number                  integer not null,
    host                            varchar(255) not null,
    port                            integer not null default 22,
    username                        varchar(200) not null,
    auth_method                     varchar(20) not null,
    credential_id                   bigint not null,
    credential_secret_kind          varchar(40) not null,
    credential_host                 varchar(255) not null,
    host_key_algorithm              varchar(40) not null,
    host_key_fingerprint_sha256     varchar(100) not null,
    based_on_version_id             bigint,
    change_reason                   varchar(500),
    config_hash                     varchar(64) not null,
    created_at                      timestamp with time zone not null,
    created_by                      varchar(100) not null,
    created_by_subject              varchar(255),
    constraint pk_connection_profile_version primary key (id),
    constraint uk_connection_profile_version_number unique (connection_profile_id, version_number),
    constraint fk_connection_profile_version_profile foreign key (connection_profile_id)
        references connection_profile (id),
    constraint fk_connection_profile_version_credential foreign key (credential_id, credential_secret_kind, credential_host)
        references external_credential (id, secret_kind, bound_host),
    constraint fk_connection_profile_version_based_on foreign key (based_on_version_id)
        references connection_profile_version (id),
    constraint ck_connection_profile_version_number check (version_number >= 1),
    constraint ck_connection_profile_version_port check (port between 1 and 65535),
    constraint ck_connection_profile_version_auth_method check (auth_method in ('PASSWORD', 'PRIVATE_KEY')),
    constraint ck_connection_profile_version_credential_host check (credential_host = host),
    constraint ck_connection_profile_version_auth_password
        check ((auth_method = 'PASSWORD') = (credential_secret_kind = 'SFTP_PASSWORD')),
    constraint ck_connection_profile_version_auth_key
        check ((auth_method = 'PRIVATE_KEY') = (credential_secret_kind = 'SSH_PRIVATE_KEY')),
    constraint ck_connection_profile_version_host_normalized
        check (length(btrim(host)) > 0
            and host = lower(host)
            and right(host, 1) <> '.'
            and host !~ '[[:space:]]'),
    constraint ck_connection_profile_version_username check (length(btrim(username)) > 0),
    constraint ck_connection_profile_version_host_key
        check (length(btrim(host_key_algorithm)) > 0 and length(btrim(host_key_fingerprint_sha256)) > 0),
    constraint ck_connection_profile_version_created_subject
        check (created_by_subject is null or created_by is not null)
);

create index idx_connection_profile_version_credential on connection_profile_version (credential_id);
create index idx_connection_profile_version_based_on on connection_profile_version (based_on_version_id);

