    event_kind            varchar(30) not null,
    task_id               bigint,
    dc_version_id         bigint,
    profile_version_id    bigint,
    outcome_code          varchar(60),
    detail                varchar(500),
    reason                varchar(500),
    source                varchar(20) not null,
    changed_by            varchar(100),
    changed_by_subject    varchar(255),
    changed_at            timestamp with time zone not null,
    constraint pk_acquisition_config_event primary key (id),
    constraint fk_acquisition_config_event_task foreign key (task_id) references catalog_import_task (id),
    constraint fk_acquisition_config_event_dc_version foreign key (dc_version_id)
        references delivery_configuration_version (id),
    constraint fk_acquisition_config_event_profile_version foreign key (profile_version_id)
        references connection_profile_version (id),
    constraint ck_acquisition_config_event_kind
        check (event_kind in ('TASK_BOUND', 'TASK_UNBOUND', 'CONNECTION_TESTED', 'HOST_KEY_SCANNED', 'RETIRED')),
    constraint ck_acquisition_config_event_source
        check ((source = 'HUMAN' and changed_by is not null)
            or (source = 'SYSTEM' and changed_by is null and changed_by_subject is null)),
    constraint ck_acquisition_config_event_subject
