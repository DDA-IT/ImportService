--changeset catalogimport:005-2-publication-bundle-batch
--comment Lidmaatschap van een batch in een bundel, op BATCHNIVEAU (design par. 2, R-BND). Een batch heeft hoogstens één actief lidmaatschap, over alle bundels heen.

-- import_link_id staat gedenormaliseerd op de koppelrij (design par. 2): de conflictquery bij
-- bevriezen (design par. 3) joint op import_link_id + identity_hash zonder telkens via import_batch te
-- moeten gaan.
--
-- active_marker is TRUE zolang het lidmaatschap actief is en NULL zodra het verwijderd is - zelfde
-- NULL-markertruc als import_batch.open_marker (002) en catalog_reference_state.active_marker (004-8).
-- uk_publication_bundle_batch_active is de kernconstraint van dit ontwerp: ze garandeert op
-- databaseniveau, ook onder gelijktijdige toevoegingen, dat een batch nooit in twee bundels tegelijk
-- actief lid is.
create table publication_bundle_batch (
    id             bigint generated by default as identity,
    bundle_id      bigint not null,
    batch_id       bigint not null,
    import_link_id bigint not null,
    added_by       varchar(100) not null,
    added_at       timestamp with time zone not null,
    removed_by     varchar(100),
    removed_at     timestamp with time zone,
    removed_reason varchar(500),
    active_marker  boolean,
    constraint pk_publication_bundle_batch primary key (id),
    constraint fk_publication_bundle_batch_bundle foreign key (bundle_id)
        references publication_bundle (id),
    constraint fk_publication_bundle_batch_batch foreign key (batch_id)
        references import_batch (id),
    constraint fk_publication_bundle_batch_link foreign key (import_link_id)
        references import_link (id),
    constraint uk_publication_bundle_batch_bundle unique (bundle_id, batch_id),
    constraint uk_publication_bundle_batch_active unique (batch_id, active_marker),
    -- FALSE zou een derde toestand invoeren die de NULL-markertruc stilzwijgend uitschakelt (zelfde
    -- redenering als ck_catalog_reference_state_active_marker in 004-8).
    constraint ck_publication_bundle_batch_marker check (active_marker is null or active_marker = true),
    -- Actief lidmaatschap: geen van de drie removed-velden gevuld, active_marker TRUE. Verwijderd
    -- lidmaatschap: alle drie gevuld, active_marker NULL. Geen tussenvorm mogelijk.
    constraint ck_publication_bundle_batch_removed check (
        (removed_by is null and removed_at is null and removed_reason is null and active_marker = true)
        or (removed_by is not null and removed_at is not null and removed_reason is not null
            and active_marker is null)
    )
);

create index idx_publication_bundle_batch_bundle on publication_bundle_batch (bundle_id);
create index idx_publication_bundle_batch_link on publication_bundle_batch (import_link_id, active_marker);

