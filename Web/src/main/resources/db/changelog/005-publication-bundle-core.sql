--changeset catalogimport:005-4-import-mutation-decision
--comment Vier additieve beslisvelden op de mutatielijst (design par. 2, R-DEC). Elke mutatie draagt haar eigen decided_by/decided_at/decided_from_status/decision_id, ook bij een groepsactie.

-- Alle vier nullable en samen leeg of samen gevuld (check hieronder): een mutatie die nog niet
-- beslist is, draagt geen van de vier. decided_from_status bewaart de status vlak voor de beslissing
-- (PLANNED of AWAITING_APPROVAL, of de tegenovergestelde eindstatus bij een herziening), zodat de
-- audit-trail leesbaar blijft zonder de append-only publication_decision te moeten joinen.
--
-- Geen decision_reason op de mutatie zelf: de reden staat één keer op publication_decision, niet
-- gedupliceerd over mogelijk honderdduizenden mutatierijen (design par. 2).
alter table import_mutation add column decided_by varchar(100);
alter table import_mutation add column decided_at timestamp with time zone;
alter table import_mutation add column decided_from_status varchar(40);
alter table import_mutation add column decision_id bigint;

alter table import_mutation add constraint fk_import_mutation_decision
    foreign key (decision_id) references publication_decision (id);

alter table import_mutation add constraint ck_import_mutation_decision_fields check (
    (decided_by is null and decided_at is null and decided_from_status is null and decision_id is null)
    or (decided_by is not null and decided_at is not null and decided_from_status is not null
        and decision_id is not null)
);

-- Een afgekeurde mutatie moet altijd naar haar beslissing (en dus haar verplichte reden) kunnen wijzen.
alter table import_mutation add constraint ck_import_mutation_rejected_decided
    check (status <> 'REJECTED' or decision_id is not null);

-- Draagt de conflictquery bij bevriezen (design par. 3): twee publiceerbare mutaties op dezelfde
-- (import_link_id, identity_hash) uit verschillende batches.
create index idx_import_mutation_link_identity_status
    on import_mutation (import_link_id, identity_hash, status);

