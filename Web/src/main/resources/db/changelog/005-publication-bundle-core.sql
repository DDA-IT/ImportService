--changeset catalogimport:005-1-publication-bundle
--comment De Publicatiebundel: eenheid van goedkeuring/bevriezing/publicatie over meerdere batches heen (design par. 2, R-BND).

-- target_mode heeft BEWUST GEEN default: een bundel moet altijd expliciet SIMULATION, TRIAL_LIBRARY
-- of PRODUCTION kiezen. Een stille default zou ofwel per ongeluk naar productie publiceren, ofwel een
-- echte productiebundel laten lijken op een proef.
--
-- De tien tellers zijn nullable bigint, net als de tellers op import_batch (par. 3a): NULL betekent
-- "niet vastgesteld" (nog niet bevroren), nooit stil 0. Ze worden pas bij bevriezen (bouwstap 4e)
-- berekend en bewaard.
--
-- content_hash gebruikt ${hash.type} (bytea/varbinary(32), zie db.changelog-master.yaml) en is enkel
-- gevuld zodra de bundel FROZEN is; de check hieronder dwingt dat af.
create table publication_bundle (
    id                       bigint generated by default as identity,
    bundle_reference         varchar(100) not null,
    description              varchar(500),
    status                   varchar(30) not null,
    target_mode              varchar(30) not null,
    target_moment            timestamp with time zone,
    publication_policy       varchar(1000),
    created_by               varchar(100) not null,
    created_at               timestamp with time zone not null,
    frozen_by                varchar(100),
    frozen_at                timestamp with time zone,
    frozen_reason            varchar(500),
    cancelled_by             varchar(100),
    cancelled_at             timestamp with time zone,
    cancelled_reason         varchar(500),
    content_hash             ${hash.type},
    idempotency_key          varchar(200) not null,
    batch_count              bigint,
    content_mutation_count   bigint,
    ready_count              bigint,
    rejected_count           bigint,
    blocked_count            bigint,
    expired_count            bigint,
    identity_incident_count  bigint,
    bulk_incident_count      bigint,
    critical_issue_count     bigint,
    warning_count            bigint,
    constraint pk_publication_bundle primary key (id),
    constraint uk_publication_bundle_reference unique (bundle_reference),
    constraint uk_publication_bundle_idempotency unique (idempotency_key),
    constraint ck_publication_bundle_status check (status in
        ('ASSEMBLING', 'FROZEN', 'CANCELLED', 'PUBLISHING', 'PARTIALLY_PUBLISHED', 'PUBLISHED',
         'PUBLICATION_FAILED')),
    constraint ck_publication_bundle_target_mode check (target_mode in
        ('SIMULATION', 'TRIAL_LIBRARY', 'PRODUCTION')),
    -- R-FRZ: bevriezen berekent en bewaart in één transactie frozen_by, frozen_at en content_hash;
    -- geen van de drie mag zonder de andere twee bestaan zodra de status FROZEN is.
    constraint ck_publication_bundle_frozen check (status <> 'FROZEN'
        or (frozen_by is not null and frozen_at is not null and content_hash is not null)),
    -- Annuleren vereist altijd een reden (R-FRZ), net als frozen_reason bij bevriezen.
    constraint ck_publication_bundle_cancelled check (status <> 'CANCELLED'
        or (cancelled_by is not null and cancelled_at is not null and cancelled_reason is not null))
);

