--changeset catalogimport:005-3-publication-decision
--comment Append-only beslissingsregister per mutatie/groep/bundel (design par. 2, R-DEC; retentie 7 jaar).

-- Eén rij per genomen beslissing, nooit bijgewerkt of verwijderd: een herziening (R-DEC) schrijft een
-- NIEUWE rij, de oude blijft staan. mutation_id is enkel gevuld bij scope MUTATION; bij GROUP/BUNDLE
-- staat de canoniek gerenderde filter/reden in selection_filter/reason en telt affected_count het
-- werkelijke aantal geraakte mutaties.
create table publication_decision (
    id               bigint generated by default as identity,
    bundle_id        bigint not null,
    mutation_id      bigint,
    decision_kind    varchar(30) not null,
    decision_scope   varchar(20) not null,
    selection_filter varchar(500),
    previous_status  varchar(40),
    new_status       varchar(40),
    affected_count   bigint not null default 1,
    decided_by       varchar(100) not null,
    decided_at       timestamp with time zone not null,
    reason           varchar(500) not null,
    constraint pk_publication_decision primary key (id),
    constraint fk_publication_decision_bundle foreign key (bundle_id)
        references publication_bundle (id),
    constraint fk_publication_decision_mutation foreign key (mutation_id)
        references import_mutation (id),
    constraint ck_publication_decision_kind check (decision_kind in
        ('APPROVE', 'REJECT', 'AUTO_APPROVE_PLANNED', 'FREEZE', 'CANCEL')),
    constraint ck_publication_decision_scope check (decision_scope in ('MUTATION', 'GROUP', 'BUNDLE')),
    -- MUTATION-scope beslist over exact één mutatie: mutation_id gevuld en affected_count = 1. Een
    -- GROUP- of BUNDLE-beslissing draagt nooit een individuele mutatieverwijzing.
    constraint ck_publication_decision_mutation check (
        (decision_scope = 'MUTATION' and mutation_id is not null and affected_count = 1)
        or (decision_scope <> 'MUTATION' and mutation_id is null)
    )
);

create index idx_publication_decision_bundle_decided on publication_decision (bundle_id, decided_at);
create index idx_publication_decision_mutation on publication_decision (mutation_id);

