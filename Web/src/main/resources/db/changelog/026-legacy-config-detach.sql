--comment G2a: append-only audit van elke loskoppeling (en later het opnieuw aansluiten): welke koppeling van welke naar welke definitie verlegd werd, door wie, waarom en uit welke ontvangst.

-- import_link bewaart geen definitiehistoriek: na het verleggen staat de vroegere definitie enkel nog in
-- import_batch.definition_revision_id (de bevroren revisie van elke oude batch) en hier. Daarom is deze tabel
-- append-only: nooit bijgewerkt, nooit verwijderd.
--   * origin_id: de herkomst (020-2) van de interface.
--   * import_link_id: de koppeling die verlegd werd (of, bij een nieuwe interface die meteen een eigen definitie
--     krijgt, de koppeling die op de kopie ontstond).
--   * from_definition_id / to_definition_id: de gedeelde definitie en de eigen kopie.
--   * receipt_id: de ontvangst waarvan de APPLY loskoppelde; nullable voor een latere handeling buiten een ontvangst.
--   * action: DETACH; REATTACH (opnieuw aansluiten) is in het model voorzien maar wordt in G2 nooit gezet (design G2a
--     punt 9).
--   * reason: de APPLY-reden (verplicht, zoals legacy_config_receipt.applied_reason).
--   * created_at/created_by/created_by_subject: wie, met koppelcheck zoals 007-4.
create table legacy_config_detachment (
    id                      bigint generated by default as identity,
    origin_id               bigint not null,
    import_link_id          bigint not null,
    from_definition_id      bigint not null,
    to_definition_id        bigint not null,
    receipt_id              bigint,
    action                  varchar(20) not null,
    reason                  varchar(500) not null,
    created_at              timestamp with time zone not null,
    created_by              varchar(100) not null,
    created_by_subject      varchar(255),
    constraint pk_legacy_config_detachment primary key (id),
    constraint fk_legacy_config_detachment_origin foreign key (origin_id) references legacy_config_origin (id),
    constraint fk_legacy_config_detachment_link foreign key (import_link_id) references import_link (id),
    constraint fk_legacy_config_detachment_from foreign key (from_definition_id) references import_definition (id),
    constraint fk_legacy_config_detachment_to foreign key (to_definition_id) references import_definition (id),
    constraint fk_legacy_config_detachment_receipt foreign key (receipt_id) references legacy_config_receipt (id),
    constraint ck_legacy_config_detachment_action check (action in ('DETACH', 'REATTACH')),
    constraint ck_legacy_config_detachment_definitions check (from_definition_id <> to_definition_id),
    constraint ck_legacy_config_detachment_reason_not_blank check (length(btrim(reason)) > 0),
    constraint ck_legacy_config_detachment_created_by_not_blank check (length(btrim(created_by)) > 0),
    constraint ck_legacy_config_detachment_created_subject
        check (created_by_subject is null or created_by is not null)
);

create index idx_legacy_config_detachment_origin on legacy_config_detachment (origin_id);
create index idx_legacy_config_detachment_link on legacy_config_detachment (import_link_id);
create index idx_legacy_config_detachment_to on legacy_config_detachment (to_definition_id);

