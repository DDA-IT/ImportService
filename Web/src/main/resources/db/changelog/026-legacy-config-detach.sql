--   * GROEP (S7, A2): group_marker = TRUE, detached_interface_code = NULL. De groepssleutel
--     (env, dossier, supplier_code, definition_content_hash) blijft uniek onder groepen: de marker staat erbij in
--     uk_legacy_config_definition_origin, en voor een groep is ze altijd TRUE.
--   * LOSGEKOPPELDE KOPIE (G2a): group_marker = NULL, detached_interface_code = de interface die loskoppelde,
--     template_definition_id = NULL (de kopie is gebaseerd op de gedeelde definitie, niet op het sjabloon). Ze mag
--     dezelfde inhoudshash hebben als haar groep of als een andere kopie: NULL botst niet in de unieke sleutel. Per
--     herkomst (env, dossier, interface) hoogstens een kopie: uk_legacy_config_definition_origin_detached.
-- De groepsherkenning (findGroup) leest enkel groepsrijen; een kopie trekt dus nooit leden aan.
--
-- De check is strenger dan "(group_marker is true) = (detached_interface_code is null)" uit het ontwerp: ook FALSE is
-- verboden, zodat er precies twee vormen bestaan en de marker nooit een derde betekenis krijgt.
alter table legacy_config_definition_origin add column detached_interface_code varchar(20);
alter table legacy_config_definition_origin add column group_marker boolean;

-- Backfill: elke bestaande rij is een groep (vóór G2a bestond er geen andere soort).
update legacy_config_definition_origin set group_marker = true;

alter table legacy_config_definition_origin add constraint ck_legacy_config_definition_origin_kind
    check ((group_marker is true and detached_interface_code is null)
        or (group_marker is null and detached_interface_code is not null));

alter table legacy_config_definition_origin add constraint ck_legacy_config_definition_origin_detached_not_blank
    check (detached_interface_code is null or length(btrim(detached_interface_code)) > 0);

-- Een losgekoppelde kopie heeft geen sjabloon (design G2a punt 6: template_definition_id = null).
alter table legacy_config_definition_origin add constraint ck_legacy_config_definition_origin_detached_template
    check (detached_interface_code is null or template_definition_id is null);

-- Gemelde constraintwijziging (design G2a): de groepssleutel krijgt group_marker erbij.
