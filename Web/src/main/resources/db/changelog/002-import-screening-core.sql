--changeset catalogimport:002-2-import-batch
--comment Eén screening van één levering onder één bevroren revisie (design par. 1).

-- open_marker is TRUE zolang de batch niet-terminaal is en NULL in SCREENED/BLOCKED/FAILED/BASELINE_ACCEPTED.
-- NULL-waarden botsen niet in een UNIQUE constraint: hoogstens een open batch per levering, op databaseniveau.
-- Tellers zijn nullable: NULL = onbekend, nooit stil 0.
create table import_batch (
    id                          bigint generated by default as identity,
    delivery_id                 bigint not null,
    import_link_id              bigint not null,
    definition_revision_id      bigint not null,
    task_run_id                 bigint,
    attempt_no                  integer not null default 1,
    status                      varchar(40) not null,
    open_marker                 boolean,
    started_at                  timestamp with time zone,
    finished_at                 timestamp with time zone,
    staged_row_count            bigint not null default 0,
    mutation_progress_row_number bigint not null default 0,
    raw_record_count            bigint,
    valid_record_count          bigint,
    rejected_record_count       bigint,
    duplicate_identity_count    bigint,
    new_count                   bigint,
    changed_count               bigint,
    unchanged_count             bigint,
    content_mutation_count      bigint,
    blocked_code                varchar(60),
    blocked_reason              varchar(500),
    created_at                  timestamp with time zone not null,
    created_by                  varchar(100),
    constraint pk_import_batch primary key (id),
    constraint uk_import_batch_attempt unique (delivery_id, definition_revision_id, attempt_no),
    constraint uk_import_batch_open unique (delivery_id, open_marker),
    constraint fk_import_batch_delivery foreign key (delivery_id) references delivery (id),
    constraint fk_import_batch_import_link foreign key (import_link_id) references import_link (id),
    constraint fk_import_batch_definition_revision foreign key (definition_revision_id) references import_definition_revision (id),
    constraint fk_import_batch_task_run foreign key (task_run_id) references task_run (id)
);

create index idx_import_batch_link_created on import_batch (import_link_id, created_at);

