--changeset catalogimport:002-6-import-mutation
--comment Centrale mutatielijst (PSIMPORT001) per batch, met idempotentiesleutel en IMPORT_MARKER (design par. 4).

create table import_mutation (
    id                          bigint generated by default as identity,
    batch_id                    bigint not null,
    delivery_id                 bigint not null,
    import_link_id              bigint not null,
    definition_revision_id      bigint not null,
    task_run_id                 bigint,
    action_type                 varchar(20) not null,
    target_domain               varchar(20) not null,
    status                      varchar(40) not null,
    status_reason               varchar(200),
    identity_supplier           varchar(200),
    identity_supplier_group     varchar(200),
    identity_supplier_reference varchar(200),
    identity_discount_code      varchar(200),
    identity_discount_state     varchar(20),
    identity_hash               ${hash.type},
    before_combined_fingerprint ${hash.type},
    after_combined_fingerprint  ${hash.type},
    domain_mask                 varchar(100),
    before_base_price           numeric(24,6),
    after_base_price            numeric(24,6),
    base_price_currency         varchar(3),
    source_state_id             bigint,
    delivery_file_id            bigint,
    source_row_number           bigint,
    result_summary              varchar(1000),
    idempotency_key             varchar(200) not null,
    created_at                  timestamp with time zone not null,
    constraint pk_import_mutation primary key (id),
    constraint uk_import_mutation_idempotency unique (idempotency_key),
    constraint fk_import_mutation_batch foreign key (batch_id) references import_batch (id),
    constraint fk_import_mutation_delivery foreign key (delivery_id) references delivery (id),
    constraint fk_import_mutation_import_link foreign key (import_link_id) references import_link (id),
    constraint fk_import_mutation_definition_revision foreign key (definition_revision_id) references import_definition_revision (id),
    constraint fk_import_mutation_task_run foreign key (task_run_id) references task_run (id),
    constraint fk_import_mutation_source_state foreign key (source_state_id) references catalog_source_state (id),
    constraint fk_import_mutation_file foreign key (delivery_file_id) references delivery_file (id),
    constraint ck_import_mutation_marker check (
        (action_type = 'IMPORT_MARKER'
            and target_domain = 'IMPORT'
            and status = 'RECORDED'
            and identity_supplier is null
            and identity_supplier_group is null
            and identity_supplier_reference is null
            and identity_hash is null)
        or (action_type in ('CREATE', 'UPDATE')
            and target_domain <> 'IMPORT'
            and identity_supplier is not null
            and identity_supplier_group is not null
            and identity_supplier_reference is not null)
    )
);

create index idx_import_mutation_batch_status on import_mutation (batch_id, status);
create index idx_import_mutation_link_identity on import_mutation (import_link_id, identity_hash);

