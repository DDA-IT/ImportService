-- Legacy-config S8a: maptabel voor de vertaling (MAP) van een veldmapping (docs/design/legacy-config-s8-design.md
-- par. 2a en 3; docs/design/legacy-config-bundle-design.md par. 4 "023-field-value-map"). Volledig ADDITIEF: geen
-- bestaande tabel, kolom of constraint wijzigt; er wordt niets gebackfilld.
--
-- Waarom een eigen tabel: een vertaaltabel in import_field_mapping.transform_config (varchar(1000), notatie
-- "values=bron>doel|...") is te klein voor legacy PSIMPDEFMAP (MAP_TOO_LARGE) en kan ';', '|' en '>' in een sleutel of
-- waarde niet uitdrukken. Een rij hier is een businessgegeven per mapping, geen vrije expressie (beslissingslog Q9).
--
-- Regels:
--   * source_value/target_value varchar(50) = legacy PSIMPDEFMAP KEY/VALUE (DS_0254); nooit afgekapt.
--   * source_value is nooit blanco (een lege sleutel vertaalt niets); target_value mag '' zijn (vertaalt naar leeg).
--   * uniek (mapping_id, source_value): een bronwaarde heeft precies een doelwaarde; uniek (mapping_id, sequence_number):
--     een vaste, herleidbare volgorde (migratie: de legacy-volgorde op NUMMER, KEY).
--   * created_at/created_by/created_by_subject zoals de mapping zelf (004-2, 007-4): wie de vertaling vastlegde.
--   * Geen "on delete cascade" (zoals elke FK in dit schema): de applicatie verwijdert de rijen vóór hun mapping.
--   * Hoofdlettergevoeligheid is geen kolom: ze blijft de instelling caseSensitive in transform_config van de mapping.
--
-- De rijen horen bij een bevroren revisie zoals de mapping zelf: ze worden enkel in een DRAFT geschreven of verwijderd.
--
-- Rollback: de tabel verdwijnt met haar rijen; een MAP-mapping zonder values= wordt dan CONFIG_TRANSFORM_INVALID.

--changeset catalogimport:023-1-import-field-value-map
--comment S8a: vertaaltabel per veldmapping (bron -> doel), legacy PSIMPDEFMAP; additief.
create table import_field_value_map (
    id                 bigint generated by default as identity,
    mapping_id         bigint not null,
    sequence_number    integer not null,
    source_value       varchar(50) not null,
    target_value       varchar(50) not null,
    created_at         timestamp with time zone not null,
    created_by         varchar(100),
    created_by_subject varchar(255),
    constraint pk_import_field_value_map primary key (id),
    constraint uk_import_field_value_map_source unique (mapping_id, source_value),
    constraint uk_import_field_value_map_sequence unique (mapping_id, sequence_number),
    constraint fk_import_field_value_map_mapping foreign key (mapping_id)
        references import_field_mapping (id),
    constraint ck_import_field_value_map_sequence
        check (sequence_number > 0),
    constraint ck_import_field_value_map_source_not_blank
        check (length(btrim(source_value)) > 0),
    constraint ck_import_field_value_map_created_subject
        check (created_by_subject is null or created_by is not null)
);

--rollback drop table import_field_value_map;
