--changeset catalogimport:020-1-legacy-config-receipt
--comment Ontvangst van een legacy-config-bundel per herkomst (environment, dossier, interface): idempotent tegenover de laatste ontvangst, hoogstens een open ontvangst per herkomst.

-- Herkomstsleutel = (origin_environment, origin_dossier, interface_code) (contract par. 1).
--   * Idempotentie (beslissingslog 2026-10-20 "Legacy-config S1: idempotentie tegenover de laatste ontvangst"): een
--     push wordt enkel vergeleken met de LAATSTE ontvangst van dezelfde herkomst (max(id)), ongeacht haar status.
--     Zelfde content_hash = 200 UNCHANGED, niets geschreven; anders altijd een nieuwe rij. Een terugkerende inhoud
--     (A -> B -> A) is dus een nieuwe ontvangst: content_hash is per herkomst bewust NIET uniek.
--     idx_legacy_config_receipt_origin_latest (niet uniek) maakt "laatste ontvangst per herkomst" goedkoop.
--   * uk_legacy_config_receipt_open: open_marker is TRUE zolang de ontvangst RECEIVED is en NULL in elke andere
--     status; NULL-waarden botsen niet, dus hoogstens een open ontvangst per herkomst. Een nieuwere ontvangst zet de
--     vorige open ontvangst op SUPERSEDED (superseded_by_receipt_id = de nieuwe). Dit is het enige
--     serialisatiepunt tussen gelijktijdige pushes. Invariant: de laatste ontvangst is nooit SUPERSEDED, een open
--     ontvangst is altijd de laatste.
-- status: RECEIVED (open) | APPLIED | SUPERSEDED | DISCARDED. APPLIED en DISCARDED worden pas vanaf S2 gezet.
-- secret_outcome (vanaf S4): NULL = er kwam geen secret mee; anders wat ermee gebeurde. In S1 wordt een bundel met
-- secret geweigerd (400), dus is secret_received altijd false.
-- received_by is "svc:<azp>" van de technische client (M2), received_by_subject diens sub.
-- Checks zijn NULL-veilig geschreven ("is true", "is not null"): een CHECK die NULL oplevert, laat de rij door.
-- superseded_by_receipt_id wordt in dezelfde transactie gezet als de status SUPERSEDED, maar NA de insert van de
-- opvolger (die bestaat pas dan); de check is daarom eenrichtings (een opvolger impliceert SUPERSEDED).
create table legacy_config_receipt (
    id                          bigint generated by default as identity,
    origin_environment          varchar(40) not null,
    origin_dossier              varchar(40) not null,
    interface_code              varchar(20) not null,
    bundle_version              integer not null,
    content_hash                varchar(64) not null,
    definition_content_hash     varchar(64),
    legacy_definition_code      varchar(10),
    bundle_json                 text not null,
    secret_received             boolean not null,
    secret_outcome              varchar(40),
    credential_id               bigint,
    status                      varchar(20) not null,
    open_marker                 boolean,
    exported_at                 timestamp with time zone not null,
    received_at                 timestamp with time zone not null,
    received_by                 varchar(100) not null,
    received_by_subject         varchar(255),
    superseded_by_receipt_id    bigint,
    applied_at                  timestamp with time zone,
    applied_by                  varchar(100),
    applied_by_subject          varchar(255),
    apply_report_json           text,
    discarded_at                timestamp with time zone,
    discarded_by                varchar(100),
    discarded_by_subject        varchar(255),
    discarded_reason            varchar(500),
    constraint pk_legacy_config_receipt primary key (id),
    constraint uk_legacy_config_receipt_open
        unique (origin_environment, origin_dossier, interface_code, open_marker),
    constraint fk_legacy_config_receipt_credential foreign key (credential_id) references external_credential (id),
    constraint fk_legacy_config_receipt_superseded_by foreign key (superseded_by_receipt_id)
        references legacy_config_receipt (id),
    constraint ck_legacy_config_receipt_status
        check (status in ('RECEIVED', 'APPLIED', 'SUPERSEDED', 'DISCARDED')),
    constraint ck_legacy_config_receipt_open_marker
        check ((status = 'RECEIVED' and open_marker is true) or (status <> 'RECEIVED' and open_marker is null)),
    constraint ck_legacy_config_receipt_bundle_version check (bundle_version >= 1),
    constraint ck_legacy_config_receipt_content_hash check (content_hash ~ '^[0-9a-f]{64}$'),
    constraint ck_legacy_config_receipt_definition_hash
        check (definition_content_hash is null or definition_content_hash ~ '^[0-9a-f]{64}$'),
    constraint ck_legacy_config_receipt_keys_not_blank
        check (length(btrim(origin_environment)) > 0 and length(btrim(origin_dossier)) > 0
            and length(btrim(interface_code)) > 0),
    constraint ck_legacy_config_receipt_secret_outcome
        check ((secret_received = false and secret_outcome is null)
            or (secret_received = true and secret_outcome is not null and secret_outcome in
                ('STORED', 'DISCARDED_ALREADY_PRESENT', 'DISCARDED_PROTOCOL_UNSUPPORTED', 'DISCARDED_NO_HOST'))),
    constraint ck_legacy_config_receipt_credential check (credential_id is null or secret_received = true),
    constraint ck_legacy_config_receipt_superseded
        check (superseded_by_receipt_id is null or (status = 'SUPERSEDED' and superseded_by_receipt_id <> id)),
    constraint ck_legacy_config_receipt_applied
        check (status <> 'APPLIED' or (applied_at is not null and applied_by is not null)),
    constraint ck_legacy_config_receipt_discarded
        check (status <> 'DISCARDED' or (discarded_at is not null and discarded_by is not null
            and discarded_reason is not null)),
    constraint ck_legacy_config_receipt_received_subject
        check (received_by_subject is null or received_by is not null),
    constraint ck_legacy_config_receipt_applied_subject
        check (applied_by_subject is null or applied_by is not null),
    constraint ck_legacy_config_receipt_discarded_subject
        check (discarded_by_subject is null or discarded_by is not null)
);

-- De laatste ontvangst per herkomst (idempotentie bij elke push).
create index idx_legacy_config_receipt_origin_latest
    on legacy_config_receipt (origin_environment, origin_dossier, interface_code, id desc);
-- De lijst (GET /receipts) filtert op status en interface_code en sorteert op received_at desc, id desc.
create index idx_legacy_config_receipt_received on legacy_config_receipt (received_at desc, id desc);
create index idx_legacy_config_receipt_interface on legacy_config_receipt (interface_code);
create index idx_legacy_config_receipt_superseded_by on legacy_config_receipt (superseded_by_receipt_id);

