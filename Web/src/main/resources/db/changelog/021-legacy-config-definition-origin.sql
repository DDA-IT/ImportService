--changeset catalogimport:020-4-legacy-config-revision-origin
--comment Welke revisie uit welke legacy-ontvangst ontstond; met de inhoudshash van wat de migratie schreef.

-- Een rij per revisie die APPLY maakte (nieuwe definitie of opvolgende DRAFT). De laatst gemigreerde revisie van een
-- definitie = de revisie met het hoogste revisienummer die hier een rij heeft.
-- definition_content_hash: de legacy-definitiehash van de ontvangst (contract par. 6.4).
-- migrated_content_hash: SHA-256 over wat de migratie op de revisie zette (de door legacy bepaalde revisievelden, alle
-- mappings, alle filters) op het moment van APPLY. Dient twee beslissingen van S2:
--   * DEFINITION_UNCHANGED: de nieuwe ontvangst levert exact dezelfde inhoud -> geen nieuwe DRAFT;
--   * MANUAL_CHANGES_SINCE_MIGRATION: de laatste revisie wijkt inhoudelijk af van wat de migratie schreef (ook een
--     handmatige wijziging aan de gemigreerde DRAFT zelf vóór haar activatie) -> geen opvolgende DRAFT.
-- Niet in de ontwerptabel van par. 4; aanvulling van de S2-bouwer (AGENT.md par. 2 principe 6), omdat de inhoud van de
-- gemigreerde revisie anders achteraf niet meer vast te stellen is.
create table legacy_config_revision_origin (
    id                          bigint generated by default as identity,
    revision_id                 bigint not null,
    receipt_id                  bigint not null,
    definition_content_hash     varchar(64) not null,
    migrated_content_hash       varchar(64) not null,
    created_at                  timestamp with time zone not null,
    constraint pk_legacy_config_revision_origin primary key (id),
    constraint uk_legacy_config_revision_origin_revision unique (revision_id),
    constraint fk_legacy_config_revision_origin_revision foreign key (revision_id)
        references import_definition_revision (id),
    constraint fk_legacy_config_revision_origin_receipt foreign key (receipt_id)
        references legacy_config_receipt (id),
    constraint ck_legacy_config_revision_origin_definition_hash
        check (definition_content_hash ~ '^[0-9a-f]{64}$'),
    constraint ck_legacy_config_revision_origin_migrated_hash check (migrated_content_hash ~ '^[0-9a-f]{64}$')
);

create index idx_legacy_config_revision_origin_receipt on legacy_config_revision_origin (receipt_id);

