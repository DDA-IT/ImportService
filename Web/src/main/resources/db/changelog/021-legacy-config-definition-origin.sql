--changeset catalogimport:020-3-legacy-config-definition-origin
--comment Welke importdefinitie de legacy-definitie (omgeving, dossier, leverancier, definitionContentHash) vertegenwoordigt; uniek per die vier.

-- Groepssleutel van M1 (optie A): (origin_environment, origin_dossier, supplier_code, definition_content_hash). In S2
-- maakt elke eerste APPLY een eigen OWN_DEFINITION en een rij hier; een tweede interface met dezelfde sleutel blokkeert
-- tot S7 (SHARED_DEFINITION_NOT_SUPPORTED). template_definition_id blijft NULL tot S7 (het REUSABLE_TEMPLATE van M1).
-- definition_content_hash wordt bij een gewijzigde legacy-definitie TER PLAATSE bijgewerkt (beslissing S2): de rij zegt
-- welke legacy-inhoud de definitie NU vertegenwoordigt; de historiek per revisie staat in legacy_config_revision_origin.
-- supplier_code = INDET Supplier = source_organisation.code van de definitie (businesscode, geen Prodis-id).
-- legacy_definition_codes: de legacy-code(s) (PSIMDHFD.Code), enkel voor het rapport.
-- Een definitie met een rij hier is "gemigreerd"; een definitie zonder rij is handmatig en nooit een migratiedoel.
create table legacy_config_definition_origin (
    id                          bigint generated by default as identity,
    origin_environment          varchar(40) not null,
    origin_dossier              varchar(40) not null,
    supplier_code               varchar(50) not null,
    definition_content_hash     varchar(64) not null,
    legacy_definition_codes     text not null,
    template_definition_id      bigint,
    import_definition_id        bigint not null,
    created_at                  timestamp with time zone not null,
    updated_at                  timestamp with time zone,
    constraint pk_legacy_config_definition_origin primary key (id),
    constraint uk_legacy_config_definition_origin
        unique (origin_environment, origin_dossier, supplier_code, definition_content_hash),
    constraint fk_legacy_config_definition_origin_template foreign key (template_definition_id)
        references import_definition (id),
    constraint fk_legacy_config_definition_origin_definition foreign key (import_definition_id)
        references import_definition (id),
    constraint ck_legacy_config_definition_origin_hash check (definition_content_hash ~ '^[0-9a-f]{64}$'),
    constraint ck_legacy_config_definition_origin_keys_not_blank
        check (length(btrim(origin_environment)) > 0 and length(btrim(origin_dossier)) > 0
            and length(btrim(supplier_code)) > 0 and length(btrim(legacy_definition_codes)) > 0)
);

create index idx_legacy_config_definition_origin_definition
    on legacy_config_definition_origin (import_definition_id);

