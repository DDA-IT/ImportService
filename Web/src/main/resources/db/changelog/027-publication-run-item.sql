--comment Run-uitbreiding voor PRODUCTION: status PUBLISHING, modus bij de start, chunk-lease en hoogstens een actieve PRODUCTION-run (P4a).
--preconditions onFail:HALT onError:HALT
--precondition-sql-check expectedResult:0 select case when count(*) > 1 then 1 else 0 end from publication_run where target_mode = 'PRODUCTION' and active_marker is not null

-- PUBLISHING komt ERBIJ; alle bestaande statussen blijven geldig. ck_publication_run_marker_status blijft ONGEMOEID: PUBLISHING valt
-- onder "niet SIMULATED/FAILED => marker TRUE", dus een PUBLISHING-run houdt het slot vast. De terminale PRODUCTION-statussen (APPLIED,
-- eventueel REJECTED_BY_PRODIS) vragen marker NULL; die check herzien we in P5c wanneer die statussen gezet worden (zoals 009 aankondigde).
alter table publication_run drop constraint ck_publication_run_status;
alter table publication_run add constraint ck_publication_run_status check (status in
    ('REQUESTED', 'PREPARING', 'PUBLISHING', 'SIMULATED', 'FAILED', 'WAITING_FOR_TARGET_CONTRACT',
     'READY_FOR_DELIVERY', 'WRITTEN_TO_PSIMPORT', 'RESULT_UNKNOWN', 'APPLIED', 'REJECTED_BY_PRODIS',
     'RECOVERY_REQUIRED'));

-- legacy_master_at_start: de modus (NONE/PRODIS/PROFAB/onbekend) bij de start; NULL = niet vastgesteld, nooit stil een default.
alter table publication_run add column legacy_master_at_start varchar(30);

-- Chunk-lease: tweede "continue" onder een geldige lease -> 409 PUBLICATION_RUN_BUSY. Beide of geen van beide.
alter table publication_run add column lease_owner varchar(100);
alter table publication_run add column lease_until timestamp with time zone;
alter table publication_run add constraint ck_publication_run_lease
    check ((lease_owner is null) = (lease_until is null));

-- Hoogstens een actieve PRODUCTION-run per installatie (A1), ook onder gelijktijdige aanvragen. "Actief" = active_marker is not null,
-- exact de niet-terminale statussen van ck_publication_run_marker_status: nu alles behalve SIMULATED en FAILED (REQUESTED, PREPARING,
-- PUBLISHING, RECOVERY_REQUIRED, RESULT_UNKNOWN, WAITING_FOR_TARGET_CONTRACT, READY_FOR_DELIVERY, WRITTEN_TO_PSIMPORT, APPLIED en
-- REJECTED_BY_PRODIS; de laatste vier of meer worden nog niet gezet). Partiele index (PostgreSQL), net als andere voorwaardelijke
-- constructies; SIMULATION- en TRIAL_LIBRARY-runs vallen erbuiten.
create unique index uk_publication_run_active_production on publication_run (target_mode)
    where target_mode = 'PRODUCTION' and active_marker is not null;

