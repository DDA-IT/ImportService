--changeset catalogimport:027-1-publication-run-item
--comment Itemregister van een PRODUCTION-run: een rij per te publiceren mutatie, de idempotentiesleutel en het resultaat (P4a).

-- Levenscyclus (design par. 2.4): PENDING -> SENT -> APPLIED | UNCHANGED | REJECTED | CONFLICT | RESULT_UNKNOWN, plus NOT_SENT
-- (item dat in deze run niet verstuurd wordt, bv. CREATE in v1). Een fout VOOR commit() in Prodis zet het item terug op PENDING met
-- last_error_code (zeker niet toegepast); een fout TIJDENS commit() of een crash tussen Prodis-commit en CI-commit geeft
-- RESULT_UNKNOWN. RESULT_UNKNOWN wordt opnieuw verstuurd met dezelfde sleutel en dezelfde bytes (reconcile-by-state).
--
-- Sleutels: idempotency_key globaal uniek (zoals publication_run); (run_id, mutation_id) = een item per mutatie per run;
-- (mutation_id, publication_attempt) = het attempt-nummer stijgt enkel na een definitief niet-toegepast resultaat (REJECTED/CONFLICT).
-- Geen Prodis-id's: de identiteit zit als businesscodes in request_json. Geen on delete cascade: auditmateriaal.
-- Hash: request_hash is hex (varchar(64)), zoals artifact_sha256.
-- sent_by is NULLABLE (een PENDING-item is nog niet verstuurd), vandaar de koppelcheck zoals 007-4.
create table publication_run_item (
    id                  bigint generated by default as identity,
    run_id              bigint not null,
    mutation_id         bigint not null,
    publication_attempt integer not null default 1,
    idempotency_key     varchar(200) not null,
    request_hash        varchar(64) not null,
    request_json        text not null,
    status              varchar(30) not null default 'PENDING',
    outcome             varchar(30),
    reason_code         varchar(60),
    reason_detail       varchar(1000),
    prior_json          text,
    result_json         text,
    warnings_json       text,
    legacy_master       varchar(30),
    last_error_code     varchar(60),
    sent_at             timestamp with time zone,
    sent_by             varchar(100),
    sent_by_subject     varchar(255),
    answered_at         timestamp with time zone,
    send_count          integer not null default 0,
    constraint pk_publication_run_item primary key (id),
    constraint fk_publication_run_item_run foreign key (run_id) references publication_run (id),
    constraint fk_publication_run_item_mutation foreign key (mutation_id) references import_mutation (id),
    constraint uk_publication_run_item_idempotency unique (idempotency_key),
    constraint uk_publication_run_item_run_mutation unique (run_id, mutation_id),
    constraint uk_publication_run_item_mutation_attempt unique (mutation_id, publication_attempt),
    constraint ck_publication_run_item_status check (status in
        ('PENDING', 'SENT', 'APPLIED', 'UNCHANGED', 'REJECTED', 'CONFLICT', 'RESULT_UNKNOWN', 'NOT_SENT')),
    constraint ck_publication_run_item_outcome check (outcome is null
        or outcome in ('APPLIED', 'UNCHANGED', 'REJECTED', 'CONFLICT')),
    constraint ck_publication_run_item_attempt check (publication_attempt >= 1),
    constraint ck_publication_run_item_send_count check (send_count >= 0),
    -- Alles wat verstuurd is (of verstuurd geweest) draagt tijdstip en minstens een verzending; PENDING na een terugval mag ze houden.
    constraint ck_publication_run_item_sent check (
        status not in ('SENT', 'APPLIED', 'UNCHANGED', 'REJECTED', 'CONFLICT', 'RESULT_UNKNOWN')
        or (sent_at is not null and send_count >= 1)),
    -- Een nooit verstuurd item: NOT_SENT heeft geen verzending en geen antwoord.
    constraint ck_publication_run_item_not_sent check (
        status <> 'NOT_SENT' or (sent_at is null and send_count = 0 and answered_at is null)),
    -- Een definitief antwoord draagt zijn tijdstip en zijn uitkomst, en de uitkomst is gelijk aan de status.
    constraint ck_publication_run_item_answered check (
        status not in ('APPLIED', 'UNCHANGED', 'REJECTED', 'CONFLICT')
        -- "outcome is not null" expliciet: "outcome = status" alleen slaagt bij NULL (zie 009, ck_publication_run_marker_status).
        or (answered_at is not null and outcome is not null and outcome = status)),
    -- Niet-definitieve statussen hebben geen uitkomst en geen antwoordtijdstip.
    constraint ck_publication_run_item_unanswered check (
        status in ('APPLIED', 'UNCHANGED', 'REJECTED', 'CONFLICT')
        or (outcome is null and answered_at is null)),
    -- REJECTED/CONFLICT zijn nooit zonder reden.
    constraint ck_publication_run_item_reason check (
        status not in ('REJECTED', 'CONFLICT') or reason_code is not null),
    -- Een subject zonder naam zou een handtekening zijn zonder ondertekenaar (zoals 007-4).
    constraint ck_publication_run_item_sent_subject check (sent_by_subject is null or sent_by is not null)
);

create index idx_publication_run_item_run_status on publication_run_item (run_id, status);

